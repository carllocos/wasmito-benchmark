#!/bin/sh
#
# Usage: latex_memory_overhead_table.sh [<output.tex>]
#
# Writes the memory overhead table of the paper (tab:memory_overhead) with,
# per dynamic analysis, the geometric mean of the per-module overhead
# (overhead_geomean) of every framework, read from
# bench_output/modules_overhead:
#   static overhead   size of the instrumented module / size of the module
#     Whamm            aggregated_metrics_whamm.csv
#                      (measure_sizes_whamm.sh)
#     Wastr.           aggregated_metrics_wastrumentation.csv
#                      (measure_sizes_wastrumentation.sh)
#     Wasmito          always 1: Wasmito leaves the module unchanged
#   dynamic overhead  (module size + heap taken by the hooks) / module size
#     Wasmito          aggregated_metrics_wasmito.csv
#                      (aggregate_heap_wasmito.sh)
# Default output: bench_output/modules_overhead/memory_overhead.tex.
#
# The rows of the table are set in ANALYSES below, one row per line of the
# form
#   <whamm analysis>|<wastrumentation analysis>|<wasmito analysis>|<row name>
# The first three are the names the frameworks give the analysis (the
# analysis column of their aggregated_metrics_*.csv; the frameworks name the
# same analysis differently, e.g. call-graph and call_graph). The last is the
# name of the row in the table. An empty name means that the framework has
# no such analysis: its cells are shown as "--" (for Wasmito both its static
# and its dynamic overhead). "tbd" means that the analysis exists but is
# still to be measured, and is shown as "tbd". An analysis that is named in
# ANALYSES but missing from its CSV is also shown as "tbd", with a warning.
# A line with only "---" draws a horizontal line between rows.
#
# The geometric means are rounded to two decimals. The table uses the
# \wasmito macro of the paper and the multirow LaTeX package.

set -e
# Force a "." decimal separator regardless of the user locale.
LC_ALL=C
export LC_ALL
ROOT_DIR=$(cd "$(dirname "$0")/.." && pwd)
OVERHEAD_DIR=$ROOT_DIR/bench_output/modules_overhead
WHAMM_CSV=$OVERHEAD_DIR/aggregated_metrics_whamm.csv
WASTR_CSV=$OVERHEAD_DIR/aggregated_metrics_wastrumentation.csv
WASMITO_CSV=$OVERHEAD_DIR/aggregated_metrics_wasmito.csv
OUT_TEX=${1:-$OVERHEAD_DIR/memory_overhead.tex}

# [whamm analysis]|[wastrumentation analysis]|[wasmito analysis]|[row name]
# (an empty analysis name: the framework has no such analysis; see above)
ANALYSES='|imix|instruction-mix|Instruction Mix
basic_blocks|basic_blocks|basic-block|Basic Block Profiling
instr_coverage|instr_coverage|instr-coverage|Instruction Coverage
branches|branches|branches|Branch Coverage
call_graph|call_graph|call-graph|Call Graph
|taint|taint|Dynamic Taint
mem_access|mem_access|mem_access|Memory Access Tracing
|crypto|cryptomining|Cryptominer Detection
|forward|forward|Forward
|denan|denan|DeNaN
|safe_heap|safe-heap|Safe Heap
icount||icount|Instruction Count
imix||imix|Instruction Categories
hotness||hotness|Hotness
cache_sim||cache_sim|Cache Simulator
loop_tracer||loop_tracer|Loop Tracer
---
|order_violation|order-violation|Order Violation
|variable_violation|variable-violation|Variable Atomicity Violation
|data_race_violation|data-race-violation|Multi-Word Violation'

for CSV in "$WHAMM_CSV" "$WASTR_CSV" "$WASMITO_CSV"; do
    if [ ! -f "$CSV" ]; then
        echo "error: '$CSV' does not exist" >&2
        exit 1
    fi
done
mkdir -p "$(dirname "$OUT_TEX")"

printf '%s\n' "$ANALYSES" | awk -F, -v whamm="$WHAMM_CSV" -v wastr="$WASTR_CSV" \
    -v wasmito="$WASMITO_CSV" '
# Reads the overhead_geomean of every analysis of `file` into geo[tool, analysis].
function load(tool, file,    line, n, f, i, a_col, g_col) {
    a_col = 0; g_col = 0
    while ((getline line < file) > 0) {
        n = split(line, f, ",")
        if (!a_col) {
            for (i = 1; i <= n; i++) {
                if (f[i] == "analysis") a_col = i
                if (f[i] == "overhead_geomean") g_col = i
            }
            if (!a_col || !g_col) {
                print "error: " file " needs the columns analysis and overhead_geomean" > "/dev/stderr"
                exit 1
            }
            continue
        }
        if (n > 1) geo[tool, f[a_col]] = f[g_col]
    }
    close(file)
}
function cell(tool, a,    file) {
    if (a == "") return "--"
    if (a == "tbd") return "tbd"
    if (!((tool, a) in geo)) {
        file = (tool == "whamm") ? whamm : (tool == "wastr") ? wastr : wasmito
        print "warning: analysis \"" a "\" is not in " file ", shown as tbd" > "/dev/stderr"
        return "tbd"
    }
    return sprintf("%.2f", geo[tool, a])
}
BEGIN {
    FS = "|"
    load("whamm", whamm); load("wastr", wastr); load("wasmito", wasmito)
    print "% Generated by scripts/latex_memory_overhead_table.sh -- do not edit by hand."
    print "% Per dynamic analysis, the geometric mean of the per-module overhead"
    print "% (overhead_geomean of bench_output/modules_overhead/aggregated_metrics_*.csv)."
    print "\\begin{table}"
    print "\\centering"
    print "\\small"
    print "\\begin{tabular}{l|c@{\\hspace{6pt}}c@{\\hspace{6pt}}c|c}"
    print "\\hline"
    print "\\multirow{2}{*}{\\textbf{Analysis}}"
    print "  & \\multicolumn{3}{c|}{\\textbf{Static overhead}}"
    print "  & \\textbf{Dynamic overhead} \\\\"
    print "  & Whamm & Wastr. & \\wasmito & \\wasmito \\\\"
    print "\\hline"
}
$0 == "---" { print "\\hline"; next }
# Fields: $1 Whamm, $2 Wastrumentation, $3 Wasmito analysis, $4 row name.
# Wasmito leaves the module unchanged, so its static overhead is always 1,
# unless it has no such analysis.
NF == 4 {
    printf "%-28s & %-5s & %-5s & %s & %s \\\\\n", $4, cell("whamm", $1), cell("wastr", $2), ($3 == "" ? "--" : "1"), cell("wasmito", $3)
}
END {
    print "\\hline"
    print "\\end{tabular}"
    print "\\label{tab:memory_overhead}"
    print "\\end{table}"
}
' > "$OUT_TEX"

echo "> Wrote $OUT_TEX"
